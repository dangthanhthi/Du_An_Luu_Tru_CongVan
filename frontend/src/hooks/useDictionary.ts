export type DictionaryType = typeof translations.vi

export const useAppDictionary = () => {
  const params = useParams()
  const lang = (params?.lang as string) === 'en' ? 'en' : 'vi'
  return {
    t: translations[lang] || translations.vi,
    locale: lang,
    isEn: lang === 'en',
    isVi: lang === 'vi'
  }
}
